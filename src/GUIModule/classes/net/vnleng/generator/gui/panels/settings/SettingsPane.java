    private void init() {
        Locale[] availableLocales = new Locale[]{Locale.ITALIAN,Locale.ENGLISH};
        Arrays.sort(availableLocales, (o1, o2) -> {
            return o1.toString().compareTo(o2.toString());
        });
        LanguagesCB.setModel(new DefaultComboBoxModel<>(availableLocales));
        Locale current = DataInitializer.getInstance().getLocale();
        LanguagesCB.setSelectedItem(current);
    }

