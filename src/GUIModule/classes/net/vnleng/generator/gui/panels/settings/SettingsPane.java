    private void SaveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveBtnActionPerformed
        // TODO add your handling code here:
        Locale selectedItem = (Locale) LanguagesCB.getSelectedItem();
        if (selectedItem != null) {
            DataInitializer.getInstance().setLocale(selectedItem);
            JOptionPane.showMessageDialog(this, TextResources.GUITextBundle.getString("ReloadToApply"), TextResources.GUITextBundle.getString("Settings"), JOptionPane.OK_OPTION);
        }
        if (listener != null) {
            listener.onCloseRequest();
        }
    }//GEN-LAST:event_SaveBtnActionPerformed

